CREATE OR REPLACE FUNCTION abstract_tracking_counter_monotonic()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'abstract tracking counters are append-only' USING ERRCODE = '42501';
  END IF;
  IF NEW.namespace_id <> OLD.namespace_id
     OR NEW.presentation_type <> OLD.presentation_type
     OR NEW.last_issued_number < OLD.last_issued_number THEN
    RAISE EXCEPTION 'abstract tracking counter cannot move backward or change key' USING ERRCODE = '23514';
  END IF;
  NEW.updated_at = clock_timestamp();
  RETURN NEW;
END;
$$;

