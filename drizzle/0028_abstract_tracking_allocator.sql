CREATE OR REPLACE FUNCTION abstract_tracking_namespace_immutable()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.locked_at IS NOT NULL OR EXISTS (
      SELECT 1 FROM abstract_tracking_allocations a
      WHERE a.event_id = OLD.event_id
    ) THEN
      RAISE EXCEPTION 'issued tracking namespace cannot be deleted' USING ERRCODE = '42501';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.locked_at IS NOT NULL AND (
    NEW.event_id <> OLD.event_id OR NEW.prefix <> OLD.prefix OR NEW.padding_width <> OLD.padding_width
  ) THEN
    RAISE EXCEPTION 'issued tracking namespace is immutable' USING ERRCODE = '23514';
  END IF;
  IF OLD.locked_at IS NOT NULL AND NEW.locked_at IS NULL THEN
    RAISE EXCEPTION 'issued tracking namespace cannot be unlocked' USING ERRCODE = '23514';
  END IF;
  NEW.updated_at = clock_timestamp();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS abstract_tracking_namespace_immutable ON abstract_tracking_namespaces;
CREATE TRIGGER abstract_tracking_namespace_immutable
BEFORE UPDATE OR DELETE ON abstract_tracking_namespaces
FOR EACH ROW EXECUTE FUNCTION abstract_tracking_namespace_immutable();

CREATE OR REPLACE FUNCTION abstract_tracking_allocate(
  p_event_id integer,
  p_presentation_type presentation_type
)
RETURNS TABLE (
  tracking_id varchar,
  event_id integer,
  presentation_type presentation_type,
  sequence_number bigint,
  prefix varchar,
  padding_width smallint
)
LANGUAGE plpgsql
VOLATILE
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_namespace abstract_tracking_namespaces%ROWTYPE;
  v_counter abstract_tracking_counters%ROWTYPE;
  v_max bigint;
  v_next bigint;
  v_marker text;
  v_tracking_id varchar(80);
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM abstract_tracking_runtime
    WHERE singleton = true AND allocator_enabled = true
  ) THEN
    RAISE EXCEPTION 'abstract tracking allocator is not enabled'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT n.* INTO v_namespace
  FROM abstract_tracking_namespaces n
  WHERE n.event_id = p_event_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'abstract tracking namespace not configured for event %', p_event_id
      USING ERRCODE = 'P0001';
  END IF;

  SELECT c.* INTO v_counter
  FROM abstract_tracking_counters c
  WHERE c.namespace_id = v_namespace.id
    AND c.presentation_type = p_presentation_type
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'abstract tracking counter not configured for event % type %', p_event_id, p_presentation_type
      USING ERRCODE = 'P0001';
  END IF;

  SELECT COALESCE(MAX(a.sequence_number), 0)
    INTO v_max
  FROM abstract_tracking_allocations a
  WHERE a.event_id = p_event_id
    AND a.presentation_type = p_presentation_type
    AND a.sequence_number IS NOT NULL;

  v_next := GREATEST(v_counter.last_issued_number, v_max) + 1;
  v_marker := CASE p_presentation_type WHEN 'oral' THEN 'O' ELSE 'P' END;

  LOOP
    v_tracking_id := v_namespace.prefix || '-' || v_marker ||
      repeat('0', GREATEST(v_namespace.padding_width - length(v_next::text), 0)) || v_next::text;

    INSERT INTO abstract_tracking_allocations (
      tracking_id, event_id, presentation_type, sequence_number, identifier_origin
    ) VALUES (
      v_tracking_id, p_event_id, p_presentation_type, v_next, 'native'
    ) ON CONFLICT ON CONSTRAINT abstract_tracking_allocations_pkey DO NOTHING;

    IF FOUND THEN
      UPDATE abstract_tracking_counters AS c
      SET last_issued_number = v_next,
          updated_at = clock_timestamp()
        WHERE c.namespace_id = v_namespace.id
        AND c.presentation_type = p_presentation_type;
      UPDATE abstract_tracking_namespaces
      SET locked_at = COALESCE(locked_at, clock_timestamp()),
          updated_at = clock_timestamp()
      WHERE id = v_namespace.id;
      RETURN QUERY SELECT v_tracking_id, p_event_id, p_presentation_type,
        v_next, v_namespace.prefix, v_namespace.padding_width;
      RETURN;
    END IF;

    v_next := v_next + 1;
    IF v_next < 0 OR v_next > 9223372036854775806 THEN
      RAISE EXCEPTION 'abstract tracking sequence exhausted' USING ERRCODE = '22003';
    END IF;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION abstract_tracking_guard_legacy_id()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_match text[];
  v_namespace abstract_tracking_namespaces%ROWTYPE;
  v_counter abstract_tracking_counters%ROWTYPE;
  v_type presentation_type;
  v_number bigint;
BEGIN
  IF NEW.tracking_id IS NULL THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1 FROM abstract_tracking_runtime
    WHERE singleton = true AND abstract_writes_paused = true
  ) THEN
    RAISE EXCEPTION 'abstract writes are paused' USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (SELECT 1 FROM abstract_tracking_allocations a WHERE a.tracking_id = NEW.tracking_id) THEN
    RETURN NEW;
  END IF;

  v_match := regexp_match(NEW.tracking_id, '^(.+)-([OP])([0-9]+)$');
  IF v_match IS NULL THEN
    RAISE EXCEPTION 'legacy tracking identifier is not in the approved format' USING ERRCODE = '23514';
  END IF;

  v_type := CASE v_match[2] WHEN 'O' THEN 'oral'::presentation_type ELSE 'poster'::presentation_type END;
  IF v_type <> NEW.presentation_type THEN
    RAISE EXCEPTION 'tracking marker does not match presentation type' USING ERRCODE = '23514';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM abstract_tracking_runtime
    WHERE singleton = true AND legacy_bridge_enabled = true
  ) THEN
    RAISE EXCEPTION 'legacy tracking writer is disabled' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_namespace
  FROM abstract_tracking_namespaces n
  WHERE n.event_id = NEW.event_id
    AND n.prefix = v_match[1]
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  v_number := v_match[3]::bigint;

  SELECT * INTO v_counter
  FROM abstract_tracking_counters c
  WHERE c.namespace_id = v_namespace.id
    AND c.presentation_type = v_type
  FOR UPDATE;

  IF FOUND AND v_number <= v_counter.last_issued_number THEN
    RAISE EXCEPTION 'legacy tracking number is below reserved floor' USING ERRCODE = '23505';
  END IF;

  IF FOUND THEN
    INSERT INTO abstract_tracking_allocations (
      tracking_id, event_id, presentation_type, sequence_number, identifier_origin, metadata
    ) VALUES (
      NEW.tracking_id, NEW.event_id, v_type, v_number, 'legacy_structured',
      jsonb_build_object('source', 'legacy_bridge')
    ) ON CONFLICT (tracking_id) DO NOTHING;
    UPDATE abstract_tracking_counters
    SET last_issued_number = GREATEST(last_issued_number, v_number),
        updated_at = clock_timestamp()
    WHERE namespace_id = v_namespace.id AND presentation_type = v_type;

    -- Pre-Release-A binaries insert the abstract with NULL and then update the
    -- identifier. Bridge that legacy write into the durable root assignment in
    -- the same transaction; no orphan allocation may commit.
    IF TG_OP = 'UPDATE' AND OLD.tracking_id IS NULL THEN
      INSERT INTO abstract_tracking_identifiers (
        tracking_id, abstract_id, event_id, presentation_type_at_assignment,
        previous_tracking_id, reason
      ) VALUES (
        NEW.tracking_id, NEW.id, NEW.event_id, NEW.presentation_type,
        NULL, 'migration_assignment'
      ) ON CONFLICT (tracking_id) DO NOTHING;
      INSERT INTO abstract_tracking_audit_events (
        event_type, event_id, abstract_id, actor_type, reason_code, after_state
      ) VALUES (
        'abstract_tracking.migration_imported', NEW.event_id, NEW.id, 'legacy_bridge',
        'legacy_bridge', jsonb_build_object('trackingId', NEW.tracking_id)
      );
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS abstracts_guard_legacy_tracking_id ON abstracts;
CREATE TRIGGER abstracts_guard_legacy_tracking_id
BEFORE INSERT OR UPDATE OF tracking_id, presentation_type ON abstracts
FOR EACH ROW EXECUTE FUNCTION abstract_tracking_guard_legacy_id();

REVOKE ALL ON FUNCTION abstract_tracking_allocate(integer, presentation_type) FROM PUBLIC;
REVOKE ALL ON FUNCTION abstract_tracking_append_assignment(varchar, integer, integer, presentation_type, varchar, abstract_tracking_assignment_reason) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'conference_api_runtime') THEN
    EXECUTE 'GRANT EXECUTE ON FUNCTION abstract_tracking_allocate(integer, presentation_type) TO conference_api_runtime';
    EXECUTE 'GRANT EXECUTE ON FUNCTION abstract_tracking_append_assignment(varchar, integer, integer, presentation_type, varchar, abstract_tracking_assignment_reason) TO conference_api_runtime';
  END IF;
END
$$;

UPDATE abstract_tracking_runtime
SET allocator_enabled = true,
    history_ready = false,
    legacy_bridge_enabled = true,
    abstract_writes_paused = true,
    write_pause_reason = 'tracking migration',
    updated_at = clock_timestamp()
WHERE singleton = true;

COMMIT;
