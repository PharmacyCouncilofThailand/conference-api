-- Manual migration: run only after read-only preflight and reviewed namespace/floor
-- batch. Do not run drizzle-kit generate/db:push for this change.
BEGIN;

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

-- The API/runtime role must not create objects in the namespace used by the
-- SECURITY DEFINER functions. Deployment roles may grant this back explicitly
-- only for a controlled migration session.
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

DO $$
BEGIN
  IF to_regclass('public.abstract_tracking_migration_batches') IS NULL
     OR NOT EXISTS (
       SELECT 1 FROM abstract_tracking_migration_batches WHERE frozen_at IS NOT NULL
     ) THEN
    RAISE EXCEPTION '0028 requires a frozen reviewed abstract-tracking manifest';
  END IF;
END
$$;

-- A prior interrupted/rehearsed run may already have installed this trigger.
-- PostgreSQL cannot alter a column type while a trigger definition depends on it.
DROP TRIGGER IF EXISTS abstracts_guard_legacy_tracking_id ON abstracts;

ALTER TABLE abstracts
  ALTER COLUMN tracking_id TYPE varchar(80);

ALTER TABLE abstracts
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS archived_by integer REFERENCES backoffice_users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS archive_reason varchar(40),
  ADD COLUMN IF NOT EXISTS archive_note text,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS archived_by integer REFERENCES backoffice_users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS archive_reason varchar(40),
  ADD COLUMN IF NOT EXISTS archive_note text;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'abstracts_id_event_unique') THEN
    ALTER TABLE abstracts ADD CONSTRAINT abstracts_id_event_unique UNIQUE (id, event_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'abstracts_archive_state_check') THEN
    ALTER TABLE abstracts ADD CONSTRAINT abstracts_archive_state_check CHECK (
      (archived_at IS NULL AND archive_reason IS NULL AND archive_note IS NULL AND archived_by IS NULL)
      OR (archived_at IS NOT NULL AND archive_reason IS NOT NULL AND btrim(archive_reason) <> '')
    );
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'events_archive_state_check') THEN
    ALTER TABLE events ADD CONSTRAINT events_archive_state_check CHECK (
      (archived_at IS NULL AND archive_reason IS NULL AND archive_note IS NULL AND archived_by IS NULL)
      OR (archived_at IS NOT NULL AND archive_reason IS NOT NULL AND btrim(archive_reason) <> '')
    );
  END IF;
END
$$;

