-- Consume the latest frozen operator-approved namespace/floor batch. Existing
-- issued namespaces cannot be changed by this statement.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM abstract_tracking_namespaces n
    JOIN abstract_tracking_manifest_namespaces m ON m.event_id = n.event_id
    JOIN abstract_tracking_migration_batches b ON b.migration_batch_id = m.migration_batch_id
    WHERE b.frozen_at IS NOT NULL
      AND b.frozen_at = (SELECT max(frozen_at) FROM abstract_tracking_migration_batches WHERE frozen_at IS NOT NULL)
      AND n.locked_at IS NOT NULL
      AND (n.prefix <> m.prefix OR n.padding_width <> m.padding_width)
  ) THEN
    RAISE EXCEPTION 'reviewed namespace conflicts with an already locked namespace';
  END IF;
END
$$;

INSERT INTO abstract_tracking_namespaces (event_id, prefix, padding_width)
SELECT m.event_id, m.prefix, m.padding_width
FROM abstract_tracking_manifest_namespaces m
JOIN abstract_tracking_migration_batches b ON b.migration_batch_id = m.migration_batch_id
WHERE b.frozen_at IS NOT NULL
  AND b.frozen_at = (SELECT max(frozen_at) FROM abstract_tracking_migration_batches WHERE frozen_at IS NOT NULL)
ON CONFLICT (event_id) DO UPDATE
SET prefix = EXCLUDED.prefix,
    padding_width = EXCLUDED.padding_width,
    updated_at = clock_timestamp()
WHERE abstract_tracking_namespaces.locked_at IS NULL;

INSERT INTO abstract_tracking_approved_floors (
  event_id, presentation_type, approved_floor, evidence_source,
  approved_by, approved_at, approval_reason
)
SELECT m.event_id, m.presentation_type, m.approved_floor, m.evidence_source,
       m.approved_by, m.approved_at, m.approval_reason
FROM abstract_tracking_manifest_floors m
JOIN abstract_tracking_migration_batches b ON b.migration_batch_id = m.migration_batch_id
WHERE b.frozen_at IS NOT NULL
  AND b.frozen_at = (SELECT max(frozen_at) FROM abstract_tracking_migration_batches WHERE frozen_at IS NOT NULL)
ON CONFLICT (event_id, presentation_type) DO UPDATE
SET approved_floor = GREATEST(abstract_tracking_approved_floors.approved_floor, EXCLUDED.approved_floor),
    evidence_source = EXCLUDED.evidence_source,
    approved_by = EXCLUDED.approved_by,
    approved_at = EXCLUDED.approved_at,
    approval_reason = EXCLUDED.approval_reason;

-- Bootstrap namespaces/counters from existing event codes. Unsafe legacy event
-- codes intentionally remain unconfigured; submit then fails closed until an
-- operator sets a reviewed namespace. Existing IDs are imported byte-for-byte.
INSERT INTO abstract_tracking_namespaces (event_id, prefix, padding_width)
SELECT e.id, e.event_code, 3
FROM events e
WHERE e.event_code ~ '^[A-Z0-9]+(?:-[A-Z0-9]+)*$'
  AND EXISTS (SELECT 1 FROM abstracts a WHERE a.event_id = e.id AND a.tracking_id IS NOT NULL)
ON CONFLICT (event_id) DO NOTHING;

INSERT INTO abstract_tracking_counters (namespace_id, presentation_type)
SELECT n.id, t.presentation_type
FROM abstract_tracking_namespaces n
CROSS JOIN (VALUES ('oral'::presentation_type), ('poster'::presentation_type)) AS t(presentation_type)
ON CONFLICT (namespace_id, presentation_type) DO NOTHING;

INSERT INTO abstract_tracking_allocations (
  tracking_id, event_id, presentation_type, sequence_number, identifier_origin, metadata
)
SELECT
  a.tracking_id,
  a.event_id,
  CASE m.parts[2] WHEN 'O' THEN 'oral'::presentation_type ELSE 'poster'::presentation_type END,
  m.parts[3]::bigint,
  'legacy_structured',
  jsonb_build_object('source', '0028_backfill')
FROM abstracts a
JOIN abstract_tracking_namespaces n ON n.event_id = a.event_id
CROSS JOIN LATERAL regexp_match(a.tracking_id, '^(.+)-([OP])([0-9]{1,18})$') AS m(parts)
WHERE a.tracking_id IS NOT NULL
  AND m.parts[1] = n.prefix
ON CONFLICT (tracking_id) DO NOTHING;

INSERT INTO abstract_tracking_allocations (
  tracking_id, event_id, identifier_origin, metadata
)
SELECT a.tracking_id, a.event_id, 'legacy_opaque', jsonb_build_object('source', '0028_backfill')
FROM abstracts a
WHERE a.tracking_id IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM abstract_tracking_allocations x WHERE x.tracking_id = a.tracking_id
  )
ON CONFLICT (tracking_id) DO NOTHING;

INSERT INTO abstract_tracking_identifiers (
  tracking_id, abstract_id, event_id, presentation_type_at_assignment, reason
)
SELECT a.tracking_id, a.id, a.event_id, a.presentation_type, 'legacy_import'
FROM abstracts a
JOIN abstract_tracking_allocations x ON x.tracking_id = a.tracking_id
WHERE a.tracking_id IS NOT NULL
ON CONFLICT (tracking_id) DO NOTHING;

UPDATE abstract_tracking_counters c
SET last_issued_number = GREATEST(
  c.last_issued_number,
  COALESCE((
    SELECT MAX(a.sequence_number)
    FROM abstract_tracking_allocations a
    JOIN abstract_tracking_namespaces n ON n.id = c.namespace_id
    WHERE a.event_id = n.event_id
      AND a.presentation_type = c.presentation_type
      AND a.sequence_number IS NOT NULL
  ), 0)
),
updated_at = clock_timestamp()
WHERE c.namespace_id IS NOT NULL;

-- A reviewed floor is authoritative evidence for deleted/exported identifiers.
-- Never lower a counter; the next value is strictly floor + 1.
UPDATE abstract_tracking_counters c
SET last_issued_number = GREATEST(c.last_issued_number, f.approved_floor),
    updated_at = clock_timestamp()
FROM abstract_tracking_namespaces n
JOIN abstract_tracking_approved_floors f ON f.event_id = n.event_id
WHERE c.namespace_id = n.id AND f.presentation_type = c.presentation_type;

INSERT INTO abstract_tracking_audit_events (
  event_type, event_id, actor_type, reason_code, after_state
)
SELECT 'abstract_tracking.floor_applied', f.event_id, 'migration', 'approved_floor',
       jsonb_build_object('presentationType', f.presentation_type, 'approvedFloor', f.approved_floor,
                          'evidenceSource', f.evidence_source, 'approvedBy', f.approved_by)
FROM abstract_tracking_approved_floors f
WHERE NOT EXISTS (
  SELECT 1 FROM abstract_tracking_audit_events a
  WHERE a.event_type = 'abstract_tracking.floor_applied'
    AND a.event_id = f.event_id
    AND a.reason_code = 'approved_floor'
    AND a.after_state ->> 'presentationType' = f.presentation_type::text
);

UPDATE abstract_tracking_namespaces n
SET locked_at = COALESCE(n.locked_at, clock_timestamp()),
    updated_at = clock_timestamp()
WHERE EXISTS (
  SELECT 1 FROM abstract_tracking_allocations a
  WHERE a.event_id = n.event_id
);

UPDATE abstract_tracking_namespaces n
SET locked_at = COALESCE(n.locked_at, clock_timestamp()),
    updated_at = clock_timestamp()
WHERE EXISTS (
  SELECT 1 FROM abstract_tracking_counters c
  JOIN abstract_tracking_approved_floors f
    ON f.event_id = n.event_id
   AND f.presentation_type = c.presentation_type
  WHERE c.namespace_id = n.id AND f.approved_floor > 0
);

