CREATE OR REPLACE FUNCTION abstract_tracking_assignment_guard()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_allocation abstract_tracking_allocations%ROWTYPE;
  v_previous abstract_tracking_identifiers%ROWTYPE;
BEGIN
  SELECT * INTO v_allocation
  FROM abstract_tracking_allocations
  WHERE tracking_id = NEW.tracking_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'tracking allocation does not exist' USING ERRCODE = '23503';
  END IF;
  IF v_allocation.event_id IS NOT NULL AND v_allocation.event_id <> NEW.event_id THEN
    RAISE EXCEPTION 'tracking allocation belongs to another event' USING ERRCODE = '23514';
  END IF;
  IF v_allocation.identifier_origin = 'native'
     AND v_allocation.presentation_type IS DISTINCT FROM NEW.presentation_type_at_assignment THEN
    RAISE EXCEPTION 'native tracking allocation type mismatch' USING ERRCODE = '23514';
  END IF;
  IF NEW.previous_tracking_id IS NULL THEN
    IF NEW.reason IN ('presentation_type_change', 'migration_normalization', 'admin_correction') THEN
      RAISE EXCEPTION 'assignment reason requires a predecessor' USING ERRCODE = '23514';
    END IF;
  ELSE
    IF NEW.reason IN ('initial_submission', 'legacy_import', 'migration_assignment') THEN
      RAISE EXCEPTION 'assignment reason cannot have a predecessor' USING ERRCODE = '23514';
    END IF;
    SELECT * INTO v_previous
    FROM abstract_tracking_identifiers
    WHERE tracking_id = NEW.previous_tracking_id;
    IF NOT FOUND OR v_previous.abstract_id <> NEW.abstract_id OR v_previous.event_id <> NEW.event_id THEN
      RAISE EXCEPTION 'tracking predecessor does not belong to the same abstract/event' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS abstract_tracking_assignment_guard ON abstract_tracking_identifiers;
CREATE TRIGGER abstract_tracking_assignment_guard
BEFORE INSERT ON abstract_tracking_identifiers
FOR EACH ROW EXECUTE FUNCTION abstract_tracking_assignment_guard();

CREATE OR REPLACE FUNCTION abstract_tracking_allocation_has_assignment()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp
AS $$
BEGIN
  IF NEW.identifier_origin <> 'recovery_tombstone'
     AND NOT EXISTS (
       SELECT 1 FROM abstract_tracking_identifiers i
       WHERE i.tracking_id = NEW.tracking_id
     ) THEN
    RAISE EXCEPTION 'tracking allocation has no assignment' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS abstract_tracking_allocation_assignment_deferred ON abstract_tracking_allocations;
CREATE CONSTRAINT TRIGGER abstract_tracking_allocation_assignment_deferred
AFTER INSERT OR UPDATE ON abstract_tracking_allocations
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION abstract_tracking_allocation_has_assignment();

CREATE OR REPLACE FUNCTION abstract_tracking_append_assignment(
  p_tracking_id varchar,
  p_abstract_id integer,
  p_event_id integer,
  p_presentation_type presentation_type,
  p_previous_tracking_id varchar,
  p_reason abstract_tracking_assignment_reason
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  v_current_tracking_id varchar(80);
BEGIN
  SELECT a.tracking_id INTO v_current_tracking_id
  FROM abstracts a
  WHERE a.id = p_abstract_id AND a.event_id = p_event_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'abstract/event assignment target not found' USING ERRCODE = '23503';
  END IF;
  IF (p_previous_tracking_id IS NULL AND v_current_tracking_id IS DISTINCT FROM p_tracking_id)
     OR (p_previous_tracking_id IS NOT NULL AND p_previous_tracking_id IS DISTINCT FROM v_current_tracking_id) THEN
    RAISE EXCEPTION 'tracking assignment predecessor is not the current abstract identifier' USING ERRCODE = '23514';
  END IF;
  INSERT INTO abstract_tracking_identifiers (
    tracking_id, abstract_id, event_id, presentation_type_at_assignment,
    previous_tracking_id, reason
  ) VALUES (
    p_tracking_id, p_abstract_id, p_event_id, p_presentation_type,
    p_previous_tracking_id, p_reason
  );
END;
$$;

